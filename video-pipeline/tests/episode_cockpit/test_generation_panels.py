def test_u33_partial_retry_keeps_other_panels(
    client: TestClient,
    source_folder: Path,
    workspace: dict[str, Path],
    gen_fake: GenFake,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    limits = ConsultationBudgetLimits(
        llm_calls_limit=12, intervals_limit=6, wall_seconds_limit=600.0
    )
    monkeypatch.setattr(api_consultation, "load_budget_limits", lambda: limits)

    def text_factory() -> Any:
        def call(message: str) -> dict[str, object]:
            return _envelope(1)

        return call

    monkeypatch.setattr(
        api_consultation, "build_consultation_llm_call", text_factory
    )
    gen_fake.fail_on = {2}
    episode_id = _create_episode(client, source_folder)

    first = _post_message(
        client, episode_id,
        _gen_ask(
            {"granted": True, "panels_max": 3, "images_max": 3},
            [{"subject": "one"}, {"subject": "two"}, {"subject": "three"}],
        ),
    )

    assert first.status_code == 200
    panels = first.json()["panels"]
    assert [p["status"] for p in panels] == ["generated", "failed", "generated"]
    assert len(gen_fake.calls) == 3  # one attempt each: never auto-retried
    failed_id = panels[1]["panel_id"]
    kept = {p["panel_id"]: p["image_ref"] for p in (panels[0], panels[2])}
    kept_bytes = {
        pid: (_episode_dir(workspace, episode_id) / ref).read_bytes()
        for pid, ref in kept.items()
    }
    base = panels[0]["base_created_at"]

    retry = client.post(
        f"/episodes/{episode_id}/consultation/panels",
        json={
            "consultation_id": first.json()["consultation_id"],
            "proposal_id": "prop-1",
            "base_created_at": base,
            "permission": {"granted": True, "panels_max": 3, "images_max": 1},
            "retry_panel_ids": [failed_id],
        },
    )

    assert retry.status_code == 200
    after = {p["panel_id"]: p for p in retry.json()["panels"]}
    assert after[failed_id]["status"] == "generated"
    assert after[failed_id]["image_ref"] is not None
    assert len(gen_fake.calls) == 4  # exactly one more attempt
    for pid, ref in kept.items():
        assert after[pid]["image_ref"] == ref
        assert (_episode_dir(workspace, episode_id) / ref).read_bytes() == kept_bytes[pid]


