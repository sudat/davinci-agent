def _post_message(
    client: TestClient, episode_id: str, body: dict[str, Any] | None = None
) -> Any:
    payload: dict[str, Any] = {"message": "落ち着いた感じにしたい"}
    if body is not None:
        payload.update(body)
    return client.post(
        f"/episodes/{episode_id}/consultation/message", json=payload
    )


def _gen_ask(
    permission: dict[str, Any], specs: list[dict[str, Any]] | None = None
) -> dict[str, Any]:
    ask: dict[str, Any] = {"generation": {"permission": permission}}
    if specs is not None:
        ask["generation"]["panel_request"] = {"specs": specs}
    return ask


def _episode_dir(workspace: dict[str, Path], episode_id: str) -> Path:
    return workspace["episodes_root"] / episode_id


def _journal_lines(episode_dir: Path, *parts: str) -> list[bytes]:
    path = episode_dir.joinpath(*parts)
    try:
        return path.read_bytes().splitlines()
    except OSError:
        return []


