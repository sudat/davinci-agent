class GenFake:
    """Fail-loud fake of the Luna generation factory (fail-loud sentinel)."""

    def __init__(self) -> None:
        self.calls: list[dict[str, Any]] = []
        self.build_calls = 0
        self.fail_on: set[int] = set()
        self.verified = True
        self.method = "model-echo-probe"
        self.reason: str | None = None
        self.model_selected: str | None = _FAKE_MODEL

    def transport(self, prompt: str, input_frame: Any, model: str) -> bytes:
        self.calls.append(
            {"prompt": prompt, "input_frame": input_frame, "model": model}
        )
        if len(self.calls) in self.fail_on:
            raise GenerationError("generation-failed", "injected panel failure")
        return _FAKE_PNG + str(len(self.calls)).encode("ascii")

    def build(self) -> Any:
        self.build_calls += 1
        return api_consultation.GenerationCall(
            transport=self.transport,
            model_selected=self.model_selected,
            verified=self.verified,
            method=self.method,
            reason=self.reason,
            probe_ran=True,
            probe_wall_seconds=0.0,
        )


