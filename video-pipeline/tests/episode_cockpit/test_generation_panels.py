# U34: judgment with panels leaves the rebuild flow unchanged
# ---------------------------------------------------------------------------


def test_u34_judgment_with_panels_never_leaks_into_policy(
    client: TestClient,
    source_folder: Path,
    workspace: dict[str, Path],
    llm_calls: list[str],
    gen_fake: GenFake,
) -> None:
    episode_id = _create_episode(client, source_folder)
    episode_dir = _episode_dir(workspace, episode_id)
    with StateStore.open(workspace["state_store"]) as store:
        while True:
            current = current_job_state(store, episode_id)
            position = MAIN_PATH.index(current.status)
            if position >= MAIN_PATH.index("PREVIEW_READY"):
                break
            apply_transition(
                store,
                episode_id,
                expected_status=current.status,
                expected_parent_hash=current.adopted_artifact_hash,
                new_status=MAIN_PATH[position + 1],
                new_artifact_hash="0" * 64,
                payload=None,
            )

    created = _post_message(
        client, episode_id,
        _gen_ask(
            {"granted": True, "panels_max": 1, "images_max": 1},
            [{"subject": "only"}],
        ),
    ).json()
    consultation_id = created["consultation_id"]
    assert len(created["panels"]) == 1

    judged = client.post(
        f"/episodes/{episode_id}/consultation/judgment",
        json={
            "consultation_id": consultation_id,
            "proposal_id": "prop-1",
            "decision": "adopt",
            "scope": {"composition": True, "appearance": False, "audio": False},
            "note": None,
        },
    )

    assert judged.status_code in (200, 202)
    policy = consultation_store.latest_adopted_policy(episode_dir)
    assert policy is not None
    dumped = json.dumps(policy.model_dump(mode="json"), ensure_ascii=False)
    assert "pnl-" not in dumped
    assert "consultation/panels" not in dumped
    assert "image_ref" not in dumped
    summary = consultation_store.policy_summary(policy)
    assert "pnl-" not in json.dumps(summary.model_dump(mode="json"))
    for proposal in judged.json()["proposals"]:
        assert "panels" not in proposal
    for entry in consultation_store.load_policy_rebuild_entries(episode_dir):
        assert "pnl-" not in json.dumps(entry.model_dump(mode="json"))


