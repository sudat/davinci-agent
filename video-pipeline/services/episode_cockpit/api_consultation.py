def _attempt_generated_panel(  # noqa: PLR0913 (explicit attempt inputs; kwargs are the attempt contract)
    *,
    episode_dir: Path,
    consultation_id: str,
    proposal: ConsultationProposalV1,
    base_created_at: str,
    panel_id: str,
    spec: PanelSpecV1,
    gen: GenerationCall,
    limits: ConsultationBudgetLimits,
) -> bool:
    """One generated-panel attempt; True when the panel landed.

    The requested row is already appended by the caller. A missing frame,
    a seam refusal, or a transport failure appends a failed row with its
    honest code and ledgers the spend — then returns False. Never
    auto-retries: one call, one attempt.
    """

    seam = _generation_seam()
    frame = _resolve_panel_frame(episode_dir, spec.frame_ref)
    if spec.frame_ref is not None and frame is None:
        append_panel(
            episode_dir,
            ConsultationPanelV1(
                consultation_id=consultation_id,
                proposal_id=proposal.proposal_id,
                panel_id=panel_id,
                base_created_at=base_created_at,
                role=spec.role,
                source_frame_ref=spec.frame_ref,
                caption=_panel_caption(spec),
                status="failed",
                error_code="generation-frame-missing",
                model_selected=gen.model_selected,
                created_at=now_stamp(),
            ),
        )
        consume_budget(
            episode_dir, consultation_id,
            llm_calls=0, intervals=0, wall_seconds=0.0,
            model_id=gen.model_selected, kind="image",
            failure_code="generation-frame-missing",
        )
        return False
    started = time.monotonic()
    try:
        blob = seam.request_panel_image(
            prompt=_panel_prompt(proposal, spec),
            input_frame=frame,
            model=gen.model_selected or "",
            permission_granted=True,
            model_verified=gen.verified,
            transport=gen.transport,
            ensure_budget=lambda: ensure_budget_available(episode_dir, limits),
        )
    except Exception as error:  # noqa: BLE001 (typed seam/budget errors → failed panel rows)
        code = getattr(error, "code", "generation-failed")
        append_panel(
            episode_dir,
            ConsultationPanelV1(
                consultation_id=consultation_id,
                proposal_id=proposal.proposal_id,
                panel_id=panel_id,
                base_created_at=base_created_at,
                role=spec.role,
                source_frame_ref=spec.frame_ref,
                caption=_panel_caption(spec),
                status="failed",
                error_code=str(code),
                model_selected=gen.model_selected,
                created_at=now_stamp(),
            ),
        )
        consume_budget(
            episode_dir, consultation_id,
            llm_calls=1, intervals=0,
            wall_seconds=time.monotonic() - started,
            model_id=gen.model_selected, kind="image",
            failure_code=str(code),
        )
        return False
    target = panel_image_path(episode_dir, panel_id)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(blob)
    try:
        rel = str(target.relative_to(episode_dir))
    except ValueError:
        rel = target.name
    append_panel(
        episode_dir,
        ConsultationPanelV1(
            consultation_id=consultation_id,
            proposal_id=proposal.proposal_id,
            panel_id=panel_id,
            base_created_at=base_created_at,
            role=spec.role,
            source_frame_ref=spec.frame_ref,
            image_ref=rel,
            caption=_panel_caption(spec),
            status="generated",
            model_selected=gen.model_selected,
            created_at=now_stamp(),
        ),
    )
    try:
        input_bytes: int | None = frame.stat().st_size if frame is not None else None
    except OSError:
        input_bytes = None
    consume_budget(
        episode_dir, consultation_id,
        llm_calls=1, intervals=0,
        wall_seconds=time.monotonic() - started,
        model_id=gen.model_selected, input_bytes=input_bytes,
        output_bytes=len(blob), kind="image",
    )
    return True


def _run_panel_batch(  # noqa: PLR0913 (explicit batch inputs; kwargs are the batch contract)
    *,
    episode_dir: Path,
    consultation_id: str,
    proposals: list[ConsultationProposalV1],
    base_created_at: str,
    specs: list[PanelSpecV1],
    gen: GenerationCall,
    limits: ConsultationBudgetLimits,
) -> str:
    """Generate one spec list against proposals; returns the honest note.

    Budget pre-checks raise BEFORE any panel attempt; per-panel failures
    append failed records and continue — never auto-retried (U37).
    """

    needed = sum(1 for spec in specs if spec.role != "real_frame") * len(proposals)
    ensure_budget_available(episode_dir, limits)
    ensure_model_call_budget_available(episode_dir, limits, gen.model_selected)
    ensure_image_budget_available(episode_dir, limits, needed)
    generated = 0
    failed = 0
    attempted = 0
    for proposal in proposals:
        for spec in specs:
            attempted += 1
            panel_id = f"pnl-{uuid.uuid4().hex[:8]}"
            if spec.role == "real_frame":
                frame = _resolve_panel_frame(episode_dir, spec.frame_ref)
                append_panel(
                    episode_dir,
                    ConsultationPanelV1(
                        consultation_id=consultation_id,
                        proposal_id=proposal.proposal_id,
                        panel_id=panel_id,
                        base_created_at=base_created_at,
                        role=spec.role,
                        source_frame_ref=spec.frame_ref,
                        caption=_panel_caption(spec),
                        status=None if frame is not None else "failed",
                        error_code=None
                        if frame is not None
                        else "generation-frame-missing",
                        model_selected=gen.model_selected,
                        created_at=now_stamp(),
                    ),
                )
                continue
            append_panel(
                episode_dir,
                ConsultationPanelV1(
                    consultation_id=consultation_id,
                    proposal_id=proposal.proposal_id,
                    panel_id=panel_id,
                    base_created_at=base_created_at,
                    role=spec.role,
                    source_frame_ref=spec.frame_ref,
                    caption=_panel_caption(spec),
                    status="requested",
                    model_selected=gen.model_selected,
                    created_at=now_stamp(),
                ),
            )
            if _attempt_generated_panel(
                episode_dir=episode_dir, consultation_id=consultation_id,
                proposal=proposal, base_created_at=base_created_at,
                panel_id=panel_id, spec=spec, gen=gen, limits=limits,
            ):
                generated += 1
            else:
                failed += 1
    total = attempted
    if failed and not generated:
        decision: Literal["granted", "refused", "failed"] = "failed"
    else:
        decision = "granted"
    if total and not failed:
        note = f"{generated}/{total}枚の生成見本を用意しました。音・動きは実動画で確認します。"
    elif generated:
        note = (
            f"{total}枚中{generated}枚できました。残り{failed}枚は失敗 — "
            "成功分は保持し、失敗分だけ再要求できます。"
        )
    else:
        note = (
            "生成見本を用意できませんでした。文章・撮影素材で相談を続けられます。"
        )
    append_generation_event(
        episode_dir,
        GenerationEventV1(
            consultation_id=consultation_id,
            created_at=now_stamp(),
            model_selected=gen.model_selected,
            verified=gen.verified,
            decision=decision,
            reason=None if decision == "granted" else "panel-batch-failed",
            note=note,
        ),
    )
    return note


