@router.post("/episodes/{episode_id}/consultation/message")
def consultation_message(
    episode_id: str, request: ConsultationMessageRequest, workspace: Workspace
) -> dict[str, object]:
    """One message → one consultation; the budget gate runs BEFORE any
    LLM call (exhausted = typed 422 with zero model contact)."""

    episode_dir = _episode_dir(workspace, episode_id)
    limits = load_budget_limits()
    ensure_budget_available(episode_dir, limits)
    model_id = _consultation_model_id()
    ensure_model_call_budget_available(episode_dir, limits, model_id)
    input_bytes = len(request.message.encode("utf-8"))
    if (
        limits.max_input_bytes_per_call is not None
        and input_bytes > limits.max_input_bytes_per_call
    ):
        consume_budget(
            episode_dir, "unassigned",
            llm_calls=0, intervals=0, wall_seconds=0.0,
            model_id=model_id, input_bytes=input_bytes,
            failure_code="consultation-input-over-cap",
        )
        raise CockpitUnprocessableError(
            "consultation-input-over-cap",
            "相談文が1回あたりの上限を超えたため、AIに送りませんでした。",
        )
    llm = build_consultation_llm_call()
    if llm is None:
        raise CockpitUnprocessableError(
            "consultation-llm-unavailable",
            "consultation proposals need the production model runtime "
            "(config/editorial-runtime.json mode=production_model with a gated "
            "transport); no heuristic fallback is provided",
        )
    started = time.monotonic()
    try:
        raw = llm(request.message)
    except Exception as error:
        consume_budget(
            episode_dir, "unassigned",
            llm_calls=1, intervals=1,
            wall_seconds=time.monotonic() - started,
            model_id=model_id, input_bytes=input_bytes,
            failure_code="consultation-llm-failed",
        )
        raise CockpitUnprocessableError(
            "consultation-llm-failed", f"the consultation model call failed: {error}"
        ) from error
    wall_seconds = time.monotonic() - started
    output_bytes = len(json.dumps(raw, ensure_ascii=False).encode("utf-8"))
    try:
        proposals = _proposals_from_response(raw)
    except CockpitUnprocessableError as error:
        consume_budget(
            episode_dir, "unassigned",
            llm_calls=1, intervals=1, wall_seconds=wall_seconds,
            model_id=model_id, input_bytes=input_bytes,
            output_bytes=output_bytes, failure_code=error.code,
        )
        raise
    if (
        limits.max_output_bytes_per_call is not None
        and output_bytes > limits.max_output_bytes_per_call
    ):
        consume_budget(
            episode_dir, "unassigned",
            llm_calls=1, intervals=1, wall_seconds=wall_seconds,
            model_id=model_id, input_bytes=input_bytes,
            output_bytes=output_bytes,
            failure_code="consultation-output-over-cap",
        )
        raise CockpitUnprocessableError(
            "consultation-output-over-cap",
            "AIの回答が1回あたりの上限を超えたため、採用せず破棄しました。",
        )
    record = ConsultationRecordV1(
        consultation_id=uuid.uuid4().hex[:12],
        created_at=now_stamp(),
        message=request.message,
    )
    append_consultation(episode_dir, record)
    proposal_set = ConsultationProposalSetV1(
        consultation_id=record.consultation_id,
        created_at=now_stamp(),
        proposals=tuple(proposals),
    )
    append_proposal_set(episode_dir, proposal_set)
    consume_budget(
        episode_dir,
        record.consultation_id,
        llm_calls=1,
        intervals=1,
        wall_seconds=wall_seconds,
        model_id=model_id,
        input_bytes=input_bytes,
        output_bytes=output_bytes,
    )
    _maybe_generate_message_panels(
        episode_dir, record, proposal_set, request.generation, limits
    )
    snapshot = workspace._require_snapshot(episode_id)  # noqa: SLF001 (mixin convention)
    return consultation_view(episode_dir, record, limits, snapshot=snapshot)


def _precheck_generation_budget(
    episode_dir: Path,
    limits: ConsultationBudgetLimits,
    needed: int,
    model_id: str | None,
) -> None:
    """Headroom for probe + image calls on the SAME ledger (never reset)."""

    ensure_budget_available(episode_dir, limits)
    ensure_model_call_budget_available(episode_dir, limits, model_id)
    ensure_image_budget_available(episode_dir, limits, needed)


def _maybe_generate_message_panels(
    episode_dir: Path,
    record: ConsultationRecordV1,
    proposal_set: ConsultationProposalSetV1,
    generation: ConsultationGenerationRequestV1 | None,
    limits: ConsultationBudgetLimits,
) -> None:
    """The optional message-time generation extension (default OFF).

    No ask → silent return (the view stays byte-identical). Every refusal
    journals an event with the honest note and keeps the text
    consultation; only a granted, in-scope, verified ask contacts the
    seam — and the probe spend is ledgered as text either way.
    """

    if generation is None or generation.permission is None:
        return
    consultation_id = record.consultation_id
    permission = generation.permission
    specs = _specs_from_request(generation.panel_request)
    proposals = list(proposal_set.proposals)
    needed = sum(1 for spec in specs if spec.role != "real_frame") * len(proposals)
    refusal = _message_generation_refusal(permission, specs, needed)
    if refusal is None:
        try:
            _precheck_generation_budget(
                episode_dir, limits, needed, _consultation_model_id()
            )
        except CockpitUnprocessableError as error:
            refusal = (
                error.code,
                ("予算の上限に達したため生成を開始しませんでした。"
                "文章・完成分で判断できます。"),
            )
    if refusal is not None:
        reason, note = refusal
        _refuse_generation(
            episode_dir, consultation_id=consultation_id, proposal_id=None,
            gen=None, reason=reason, note=note,
        )
        return
    gen = build_generation_call()
    if gen.probe_ran:
        consume_budget(
            episode_dir, consultation_id,
            llm_calls=1, intervals=0, wall_seconds=gen.probe_wall_seconds,
            model_id=gen.model_selected, kind="text",
            failure_code=None if gen.verified else "generation-model-unverified",
        )
    if not gen.verified:
        _refuse_generation(
            episode_dir, consultation_id=consultation_id, proposal_id=None,
            gen=gen, reason="generation-model-unverified",
            note="生成モデルの確認が取れませんでした"
            f"({gen.reason})。生成は0回で止め、文章のみで続けます。",
        )
        return
    try:
        _run_panel_batch(
            episode_dir=episode_dir, consultation_id=consultation_id,
            proposals=proposals, base_created_at=proposal_set.created_at,
            specs=specs, gen=gen, limits=limits,
        )
    except CockpitUnprocessableError as error:
        _refuse_generation(
            episode_dir, consultation_id=consultation_id, proposal_id=None,
            gen=gen, reason=error.code,
            note="予算の上限に達したため生成を開始しませんでした。"
            "文章・完成分で判断できます。",
        )


def _message_generation_refusal(
    permission: GenerationPermissionV1,
    specs: list[PanelSpecV1],
    needed: int,
) -> tuple[str, str] | None:
    """The pre-probe refusal for a message-time ask (None = in scope)."""

    if not permission.granted:
        return (
            "generation-permission-not-granted",
            "生成の許可がないため、文章のみで相談を続けます。",
        )
    if not specs:
        return (
            "generation-needs-confirmation",
            ("生成の対象が未確定のため開始しませんでした。"
            "具体的な場面・変更点を示して再要求できます。"),
        )
    if len(specs) > permission.panels_max or len(specs) > MAX_PANELS_PER_PROPOSAL:
        return (
            "generation-out-of-scope",
            (f"許可は1案あたり{permission.panels_max}枚までです。"
            f"{len(specs)}枚の要求は範囲外のため0回で止めました。"
            "確認後に再要求できます。"),
        )
    if needed > permission.images_max:
        return (
            "generation-out-of-scope",
            (f"今回の許可は画像{permission.images_max}回分までです。"
            f"必要は{needed}回のため0回で止めました。確認後に再要求できます。"),
        )
    return None


def _require_fresh_generation_base(
    episode_dir: Path,
    consultation_id: str,
    base_created_at: str,
) -> ConsultationProposalSetV1:
    """U38: a moved proposal base refuses the re-request (409, no overwrite)."""

    latest_set = load_latest_proposal_sets(episode_dir).get(consultation_id)
    if latest_set is None or latest_set.created_at != base_created_at:
        current = latest_set.created_at if latest_set is not None else "no proposal set"
        raise CockpitConflictError(
            "generation-stale",
            f"the proposal set moved after this generation base (requested "
            f"base {base_created_at}, current {current}); re-request against "
            "the current table — the old result never overwrites it",
        )
    return latest_set


def _consume_probe_budget(
    episode_dir: Path, consultation_id: str, gen: GenerationCall
) -> None:
    if gen.probe_ran:
        consume_budget(
            episode_dir, consultation_id,
            llm_calls=1, intervals=0, wall_seconds=gen.probe_wall_seconds,
            model_id=gen.model_selected, kind="text",
            failure_code=None if gen.verified else "generation-model-unverified",
        )


def _refuse_panels_with_view(  # noqa: PLR0913 (explicit refusal fields; kwargs are the refusal contract)
    episode_dir: Path,
    record: ConsultationRecordV1,
    limits: ConsultationBudgetLimits,
    *,
    proposal_id: str | None,
    gen: GenerationCall | None,
    reason: str,
    note: str,
    snapshot: JobSnapshot | None = None,
) -> dict[str, object]:
    _refuse_generation(
        episode_dir, consultation_id=record.consultation_id,
        proposal_id=proposal_id, gen=gen, reason=reason, note=note,
    )
    return consultation_view(episode_dir, record, limits, snapshot=snapshot)


@router.post("/episodes/{episode_id}/consultation/panels")
def consultation_panels(
    episode_id: str, request: ConsultationPanelsRequestV1, workspace: Workspace
) -> dict[str, object]:
    """Explicit panel (re-)request: new specs or failed-panel retries.

    Budget gate first (same cumulative ledger, never reset). The stale
    base is a typed 409 with zero writes; every other refusal journals
    an event and returns the text view with the honest note. Retries
    append same-panel_id outcome rows (append-only, no overwrite) and
    never auto-retry — one explicit request, one attempt per panel.
    """

    episode_dir = _episode_dir(workspace, episode_id)
    limits = load_budget_limits()
    record = require_consultation(episode_dir, request.consultation_id)
    proposal = require_proposal(
        episode_dir, request.consultation_id, request.proposal_id
    )
    _require_fresh_generation_base(
        episode_dir, request.consultation_id, request.base_created_at
    )
    permission = request.permission
    snapshot = workspace._require_snapshot(episode_id)  # noqa: SLF001 (mixin convention)
    if permission is None or not permission.granted:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=None, reason="generation-permission-not-granted",
            note="生成の許可がないため、文章のみで相談を続けます。",
            snapshot=snapshot,
        )
    panels = load_panels(episode_dir, request.consultation_id)
    mine = [panel for panel in panels if panel.proposal_id == request.proposal_id]
    if request.retry_panel_ids and _specs_from_request(request.panel_request):
        raise CockpitUnprocessableError(
            "generation-mixed-request",
            "retry_panel_ids and a new panel_request cannot be combined; "
            "send the retry and the new ask separately",
        )
    if request.retry_panel_ids:
        return _retry_requested_panels(
            episode_dir=episode_dir, record=record, proposal=proposal,
            request=request, permission=permission, mine=mine,
            limits=limits, snapshot=snapshot,
        )
    return _request_new_panels(
        episode_dir=episode_dir, record=record, proposal=proposal,
        request=request, permission=permission, mine=mine,
        limits=limits, snapshot=snapshot,
    )


def _request_new_panels(  # noqa: PLR0913 (explicit new-ask inputs; kwargs are the ask contract)
    *,
    episode_dir: Path,
    record: ConsultationRecordV1,
    proposal: ConsultationProposalV1,
    request: ConsultationPanelsRequestV1,
    permission: GenerationPermissionV1,
    mine: list[ConsultationPanelV1],
    limits: ConsultationBudgetLimits,
    snapshot: JobSnapshot,
) -> dict[str, object]:
    """Fresh specs against one proposal within scope (0 calls when refused)."""

    specs = _specs_from_request(request.panel_request)
    active = [panel for panel in mine if panel.status != "failed"]
    needed = sum(1 for spec in specs if spec.role != "real_frame")
    refusal = _new_panels_refusal(specs, active, permission, needed)
    if refusal is None:
        try:
            _precheck_generation_budget(
                episode_dir, limits, needed, _consultation_model_id()
            )
        except CockpitUnprocessableError as error:
            refusal = (
                error.code,
                ("予算の上限に達したため生成を開始しませんでした。"
                "文章・完成分で判断できます。"),
            )
    if refusal is not None:
        reason, note = refusal
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=None, reason=reason, note=note,
            snapshot=snapshot,
        )
    gen = build_generation_call()
    _consume_probe_budget(episode_dir, request.consultation_id, gen)
    if not gen.verified:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=gen, reason="generation-model-unverified",
            note="生成モデルの確認が取れませんでした"
            f"({gen.reason})。生成は0回で止め、文章のみで続けます。",
            snapshot=snapshot,
        )
    try:
        _run_panel_batch(
            episode_dir=episode_dir, consultation_id=request.consultation_id,
            proposals=[proposal], base_created_at=request.base_created_at,
            specs=specs, gen=gen, limits=limits,
        )
    except CockpitUnprocessableError as error:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=gen, reason=error.code,
            note="予算の上限に達したため生成を開始しませんでした。"
            "文章・完成分で判断できます。",
            snapshot=snapshot,
        )
    return consultation_view(episode_dir, record, limits, snapshot=snapshot)


def _new_panels_refusal(
    specs: list[PanelSpecV1],
    active: list[ConsultationPanelV1],
    permission: GenerationPermissionV1,
    needed: int,
) -> tuple[str, str] | None:
    """The pre-probe refusal for a fresh panels ask (None = in scope)."""

    if not specs:
        return (
            "generation-needs-confirmation",
            ("生成の対象が未確定のため開始しませんでした。"
            "具体的な場面・変更点を示して再要求できます。"),
        )
    if len(active) + len(specs) > MAX_PANELS_PER_PROPOSAL or (
        len(specs) > permission.panels_max
    ):
        return (
            "generation-out-of-scope",
            (f"1案あたり最大{MAX_PANELS_PER_PROPOSAL}枚・"
            f"許可{permission.panels_max}枚の範囲を超えるため0回で止めました。"
            "確認後に再要求できます。"),
        )
    if needed > permission.images_max:
        return (
            "generation-out-of-scope",
            (f"今回の許可は画像{permission.images_max}回分までです。"
            f"必要は{needed}回のため0回で止めました。確認後に再要求できます。"),
        )
    return None


def _retry_requested_panels(  # noqa: PLR0913 (explicit retry inputs; kwargs are the retry contract)
    *,
    episode_dir: Path,
    record: ConsultationRecordV1,
    proposal: ConsultationProposalV1,
    request: ConsultationPanelsRequestV1,
    permission: GenerationPermissionV1,
    mine: list[ConsultationPanelV1],
    limits: ConsultationBudgetLimits,
    snapshot: JobSnapshot,
) -> dict[str, object]:
    """Regenerate exactly the named failed/requested panels (U33/U37)."""

    by_id = {panel.panel_id: panel for panel in mine}
    pairs: list[tuple[str, PanelSpecV1]] = []
    for panel_id in request.retry_panel_ids:
        saved = by_id.get(panel_id)
        if saved is None:
            raise CockpitUnprocessableError(
                "consultation-panel-not-found",
                f"consultation {request.consultation_id} has no panel {panel_id}",
            )
        if saved.status not in ("failed", "requested"):
            raise CockpitUnprocessableError(
                "generation-panel-not-retryable",
                f"panel {panel_id} is {saved.status}; only failed/requested "
                "panels take an explicit re-request",
            )
        if saved.base_created_at != request.base_created_at:
            raise CockpitConflictError(
                "generation-stale",
                f"panel {panel_id} was generated against a moved base; "
                "re-request against the current table",
            )
        pairs.append((
            panel_id,
            PanelSpecV1(
                frame_ref=saved.source_frame_ref,
                role=saved.role,
                subject=saved.caption.subject or None,
                scene_note=saved.caption.scene_note or None,
                changes=saved.caption.changes or None,
            ),
        ))
    needed = sum(1 for _, spec in pairs if spec.role != "real_frame")
    if needed > permission.images_max:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=None, reason="generation-out-of-scope",
            note=f"今回の許可は画像{permission.images_max}回分までです。"
            f"必要は{needed}回のため0回で止めました。確認後に再要求できます。",
            snapshot=snapshot,
        )
    try:
        _precheck_generation_budget(
            episode_dir, limits, needed, _consultation_model_id()
        )
    except CockpitUnprocessableError as error:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=None, reason=error.code,
            note="予算の上限に達したため再要求を開始しませんでした。"
            "文章・完成分で判断できます。",
            snapshot=snapshot,
        )
    gen = build_generation_call()
    _consume_probe_budget(episode_dir, request.consultation_id, gen)
    if not gen.verified:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=gen, reason="generation-model-unverified",
            note="生成モデルの確認が取れませんでした"
            f"({gen.reason})。生成は0回で止め、文章のみで続けます。",
            snapshot=snapshot,
        )
    try:
        _run_panel_retries(
            episode_dir=episode_dir, consultation_id=request.consultation_id,
            proposal=proposal, base_created_at=request.base_created_at,
            pairs=pairs, gen=gen, limits=limits,
        )
    except CockpitUnprocessableError as error:
        return _refuse_panels_with_view(
            episode_dir, record, limits, proposal_id=request.proposal_id,
            gen=gen, reason=error.code,
            note="予算の上限に達したため再要求を開始しませんでした。"
            "文章・完成分で判断できます。",
            snapshot=snapshot,
        )
    return consultation_view(episode_dir, record, limits, snapshot=snapshot)


def _run_panel_retries(  # noqa: PLR0913 (explicit retry inputs; kwargs are the retry contract)
    *,
    episode_dir: Path,
    consultation_id: str,
    proposal: ConsultationProposalV1,
    base_created_at: str,
    pairs: list[tuple[str, PanelSpecV1]],
    gen: GenerationCall,
    limits: ConsultationBudgetLimits,
) -> None:
    """One attempt per named panel under the SAME panel_id (append-only)."""

    ensure_budget_available(episode_dir, limits)
    ensure_model_call_budget_available(episode_dir, limits, gen.model_selected)
    ensure_image_budget_available(
        episode_dir, limits,
        sum(1 for _, spec in pairs if spec.role != "real_frame"),
    )
    for panel_id, spec in pairs:
        if spec.role == "real_frame":
            frame = _resolve_panel_frame(episode_dir, spec.frame_ref)
            append_panel(
                episode_dir,
                ConsultationPanelV1(
                    consultation_id=consultation_id,
                    proposal_id=proposal.proposal_id,
                    panel_id=panel_id,
                    base_created_at=base_created_at,
                    role=spec.role,
                    source_frame_ref=spec.frame_ref,
                    caption=_panel_caption(spec),
                    status=None if frame is not None else "failed",
                    error_code=None
                    if frame is not None
                    else "generation-frame-missing",
                    model_selected=gen.model_selected,
                    created_at=now_stamp(),
                ),
            )
            continue
        _attempt_generated_panel(
            episode_dir=episode_dir, consultation_id=consultation_id,
            proposal=proposal, base_created_at=base_created_at,
            panel_id=panel_id, spec=spec, gen=gen, limits=limits,
        )
    append_generation_event(
        episode_dir,
        GenerationEventV1(
            consultation_id=consultation_id,
            proposal_id=proposal.proposal_id,
            created_at=now_stamp(),
            model_selected=gen.model_selected,
            verified=gen.verified,
            decision="granted",
            note="失敗分の再要求を実行しました。他のコマ・選択は保たれています。",
        ),
    )


@router.get("/episodes/{episode_id}/consultation/panels/{panel_id}")
def consultation_panel_file(
    episode_id: str, panel_id: str, workspace: Workspace
) -> FileResponse:
    """Serve one generated panel's bytes (episode-relative, panels dir only)."""

    episode_dir = _episode_dir(workspace, episode_id)
    try:
        root = episode_dir.resolve()
    except OSError as error:
        raise CockpitUnprocessableError(
            "consultation-panel-not-found", f"no panel {panel_id} is served"
        ) from error
    for record in load_consultations(episode_dir):
        for panel in load_panels(episode_dir, record.consultation_id):
            if panel.panel_id != panel_id or panel.image_ref is None:
                continue
            candidate = episode_dir / panel.image_ref
            try:
                resolved = candidate.resolve()
            except OSError:
                continue
            if not resolved.is_relative_to(root) or resolved.suffix != ".png":
                continue
            if resolved.is_file():
                return FileResponse(
                    resolved, media_type="image/png", filename=f"{panel_id}.png"
                )
    raise CockpitNotFoundError(
        "consultation-panel-not-found", f"no panel {panel_id} is served"
    )


def _recover_unreserved_judgment(
    workspace: CockpitWorkspace,
    episode_id: str,
    episode_dir: Path,
    judgment_id: str,
) -> str:
    """One crash-window recovery step for a re-sent (deduped) judgment.

    Returns "completed" when the re-send provably found no reservation
    attempt (no rebuild-log row at all) for a still-latest adoptable
    judgment with nothing running — the missing reservation is then
    completed inline. Returns "deferred_running" when another rebuild
    is active (the judgment stays saved-unreserved; the caller guides
    a post-stop re-send instead of duplicating). Anything else —
    unresolvable policy, superseded adoption, ambiguous rows — is an
    honest stop: no reservation is attempted and "stopped" is returned.
    """

    try:
        policy_for_judgment(episode_dir, judgment_id)
    except Exception:  # noqa: BLE001 (unresolvable judgment: stop honestly)
        return "stopped"
    latest = latest_adopted_policy(episode_dir)
    if latest is None or latest.judgment_id != judgment_id:
        return "stopped"
    linked = [
        entry
        for entry in load_policy_rebuild_entries(episode_dir)
        if entry.judgment_id == judgment_id
    ]
    if linked:
        return "stopped"
    snapshot = workspace._require_snapshot(episode_id)  # noqa: SLF001 (mixin convention)
    if selection_rebuild_active(episode_dir, snapshot.stage_runs):
        return "deferred_running"
    try:
        workspace.record_consultation_rebuild(episode_id, judgment_id=judgment_id)
    except Exception:  # noqa: BLE001 (conflict/frozen/unready: stop honestly)
        return "stopped"
    return "completed"


def _consultation_full_authorization(
    episode_id: str,
    episode_dir: Path,
    record: ConsultationRecordV1,
    request: ConsultationJudgmentRequest,
    workspace: Workspace,
) -> JSONResponse:
    """One bound 全編へ authorization with a zero-downstream resend (P1-2).

    The first send binds the authorization to the current head + adopted
    policy + the EXPLICITLY NAMED sample; a re-send of the same
    authorization returns the existing row with no render, no budget
    write, no spawn, and no commit. A moved target under the same
    operation id surfaces as the store's typed 409. An unspecified,
    nonexistent, or other-consultation sample_id is a typed 422.
    """

    if request.proposal_id is not None:
        raise CockpitUnprocessableError(
            "consultation-judgment-proposal-unexpected",
            "全編への承認は相談全体への判断です。proposal_idを指定せずに送ってください。",
        )
    append_full_authorization_once(
        episode_dir,
        consultation_id=request.consultation_id,
        sample_id=request.sample_id,
        scope=request.scope,
        note=request.note,
        operation_id=request.operation_id,
    )
    limits = load_budget_limits()
    snapshot = workspace._require_snapshot(episode_id)  # noqa: SLF001 (mixin convention)
    return JSONResponse(
        status_code=200,
        content=consultation_view(episode_dir, record, limits, snapshot=snapshot),
    )


@router.post("/episodes/{episode_id}/consultation/judgment")
def consultation_judgment(
    episode_id: str, request: ConsultationJudgmentRequest, workspace: Workspace
) -> JSONResponse:
    """Append an adoption judgment; an adoptable one schedules a rebuild.

    Validation is unchanged (unknown words → 4xx, unknown consultation →
    404, unknown proposal → 422). A byte-identical resend of the latest
    effective adoption reuses the existing judgment with zero writes and
    zero spawns; the HTTP status mirrors the existing rebuild state
    (requested|running → 202, none|succeeded|failed → 200). When the
    appended judgment is adopt|revise with a non-empty scope AND the
    extracted latest policy is this judgment, a SELECTION rebuild is
    scheduled through the existing reservation machinery (202 with the
    view). Otherwise — reject/both_wrong/delegate, empty scope, no
    resolvable proposal, or a rebuild already running — the judgment is
    recorded and the view returns unchanged-shape 200. The rebuild
    consumes no consultation LLM budget. The explicit 全編へ
    (``full_authorized``) binds to the current head + adopted policy +
    the explicitly named sample instead, and its re-send returns the
    existing row with zero downstream work (200).
    """

    episode_dir = _episode_dir(workspace, episode_id)
    limits = load_budget_limits()
    record = require_consultation(episode_dir, request.consultation_id)
    if request.decision == "full_authorized":
        return _consultation_full_authorization(
            episode_id, episode_dir, record, request, workspace
        )
    if request.proposal_id is not None:
        require_proposal(episode_dir, request.consultation_id, request.proposal_id)
    judgment, appended = append_effective_judgment_once(
        episode_dir,
        consultation_id=request.consultation_id,
        proposal_id=request.proposal_id,
        decision=request.decision,
        scope=request.scope,
        note=request.note,
        operation_id=request.operation_id,
    )
    judgment_id = judgment.judgment_id
    snapshot = workspace._require_snapshot(episode_id)  # noqa: SLF001 (mixin convention)
    if not appended:
        recovery = _recover_unreserved_judgment(
            workspace, episode_id, episode_dir, judgment_id
        )
        if recovery == "completed":
            refreshed = workspace._require_snapshot(episode_id)  # noqa: SLF001
            return JSONResponse(
                status_code=202,
                content=consultation_view(
                    episode_dir, record, limits, snapshot=refreshed
                ),
            )
        try:
            policy = policy_for_judgment(episode_dir, judgment_id)
        except Exception:  # noqa: BLE001 (unresolvable duplicate falls back to latest)
            policy = latest_adopted_policy(episode_dir)
        state = derive_policy_rebuild(
            episode_dir, policy, snapshot.stage_runs
        ).get("status")
        content = consultation_view(
            episode_dir, record, limits, snapshot=snapshot
        )
        if recovery == "deferred_running":
            content = {
                **content,
                "reservation_recovery": {
                    "status": "deferred_running",
                    "judgment_id": judgment_id,
                    "detail": (
                        "実行中の作り直しがあるため、この判断の予約はまだです。"
                        "実行中の処理が終わってから同じ内容をもう一度送ると、"
                        "重複なく予約します。"
                    ),
                },
            }
        return JSONResponse(
            status_code=202 if state in ("requested", "running") else 200,
            content=content,
        )
    policy = latest_adopted_policy(episode_dir)
    scope_adopted = (
        request.scope.composition or request.scope.appearance or request.scope.audio
    )
    if (
        request.decision in ("adopt", "revise")
        and scope_adopted
        and policy is not None
        and policy.judgment_id == judgment_id
        and not selection_rebuild_active(episode_dir, snapshot.stage_runs)
    ):
        try:
            workspace.record_consultation_rebuild(episode_id, judgment_id=judgment_id)
        except CockpitConflictError:
            pass
        else:
            refreshed = workspace._require_snapshot(episode_id)  # noqa: SLF001
            return JSONResponse(
                status_code=202,
                content=consultation_view(
                    episode_dir, record, limits, snapshot=refreshed
                ),
            )
    return JSONResponse(
        status_code=200,
        content=consultation_view(episode_dir, record, limits, snapshot=snapshot),
    )


