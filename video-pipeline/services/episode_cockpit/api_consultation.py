type StringList = Annotated[tuple[str, ...], BeforeValidator(tuple)]


class PanelSpecV1(StrictModel):
    """One concrete panel ask: a real-frame carry or a generated variant.

    ``role`` ``real_frame`` names an extracted real frame (no generation
    call); ``a``/``b`` are same-frame A/B variants (U40). A real_frame
    without ``frame_ref`` is a boundary validation failure (fail-loud,
    never a silent generation).
    """

    frame_ref: str | None = None
    role: Literal["a", "b", "real_frame"] = "a"
    subject: str | None = None
    scene_note: str | None = None
    changes: str | None = None

    @model_validator(mode="after")
    def _require_frame_for_real(self) -> PanelSpecV1:
        if self.role == "real_frame" and not self.frame_ref:
            raise ValueError("role real_frame needs a frame_ref naming the real frame")
        return self


