def _proposals_from_response(raw: dict) -> list[ConsultationProposalV1]:
    """Parse the envelope and cap at 2; NOTHING usable → typed honest 422."""

    try:
        envelope = ConsultationLlmEnvelope.model_validate(raw)
    except ValidationError as error:
        raise CockpitUnprocessableError(
            "consultation-llm-failed",
            f"the consultation model response was not a usable proposal set: {error}",
        ) from error
    proposals = list(envelope.proposals)
    if len(proposals) > _MAX_PROPOSALS:
        _LOGGER.warning(
            "consultation: capping proposals to the first %s of %s",
            _MAX_PROPOSALS,
            len(proposals),
        )
        proposals = proposals[:_MAX_PROPOSALS]
    return [
        ConsultationProposalV1(
            proposal_id=f"prop-{index}",
            title=proposal.title,
            summary=proposal.summary,
            details=proposal.details,
        )
        for index, proposal in enumerate(proposals, start=1)
    ]


def _openai_consultation_call(
    environment: Mapping[str, str], pin: dict[str, object] | None, model_id: str
) -> ConsultationLlmCall | None:
    if not environment.get(_API_KEY_ENV) or environment.get(_NETWORK_ENV) != "1":
        return None
    try:
        from services.cli.live_editorial_v2 import (  # noqa: PLC0415 (lazy CLI-side transport)
            make_http_post,
        )
    except ImportError as error:
        _LOGGER.warning("consultation: transport unavailable, diagnostic mode (%s)", error)
        return None
    try:
        http_post = make_http_post()
    except Exception as error:  # noqa: BLE001 (tolerant factory: wiring failure degrades to diagnostic mode)
        _LOGGER.warning("consultation: transport construction failed (%s)", error)
        return None
    endpoint = pin.get("endpoint") if pin is not None else None
    url = endpoint if isinstance(endpoint, str) and endpoint else _PINNED_ENDPOINT

    def call(message: str) -> dict:
        payload = json.dumps(
            {
                "model": model_id,
                "input": [
                    {"role": "system", "content": _CONSULTATION_INSTRUCTIONS},
                    {"role": "user", "content": _data_block(message)},
                ],
                "text": {
                    "format": {
                        "type": "json_schema",
                        "name": "cockpit-consultation-proposals-v1",
                        "strict": True,
                        "schema": ConsultationLlmEnvelope.model_json_schema(),
                    }
                },
            },
            ensure_ascii=False,
        ).encode("utf-8")
        return _parse_proposal_response(
            http_post(
                url=url,
                headers={"Content-Type": "application/json"},
                body=payload,
                timeout_s=_TRANSPORT_TIMEOUT_SECONDS,
            )
        )

    return call


def _codex_consultation_call(model_id: str) -> ConsultationLlmCall | None:
    try:
        from services.cli.live_editorial_codex import (  # noqa: PLC0415 (lazy CLI-side transport)
            make_codex_runner,
        )
        from services.editorial_v2.model_provider import (  # noqa: PLC0415
            extract_json_object,
        )
    except ImportError as error:
        _LOGGER.warning("consultation: codex transport unavailable (%s)", error)
        return None
    try:
        runner = make_codex_runner()
    except Exception as error:  # noqa: BLE001 (gate refusal degrades to diagnostic mode; never raises)
        _LOGGER.warning("consultation: codex transport gated (%s)", error)
        return None

    def call(message: str) -> dict:
        prompt = _consultation_prompt(message)
        # Consultation is TEXT-only by contract: images=() ALWAYS — no
        # frame pixels, no image generation anywhere in this slice.
        return extract_json_object(
            runner(
                prompt,
                model=model_id,
                images=(),
                timeout_s=_CODEX_TRANSPORT_TIMEOUT_SECONDS,
            )
        )

    return call


def _resolve_runtime_config_path(
    runtime_path: Path | None, environment: Mapping[str, str]
) -> Path:
    """Precedence mirrored from ``episode_runner_editorial._resolve_config_path``:
    explicit ``runtime_path`` > ``EDITORIAL_RUNTIME_CONFIG`` env > repo default."""

    if runtime_path is not None:
        return runtime_path
    from_env = environment.get(_EDITORIAL_RUNTIME_ENV)
    if from_env:
        return Path(from_env)
    return _CONFIG_ROOT / RUNTIME_CONFIG_RELATIVE


def build_consultation_llm_call(
    *,
    runtime_path: Path | None = None,
    pin_path: Path | None = None,
    env: Mapping[str, str] | None = None,
) -> ConsultationLlmCall | None:
    """Tolerant factory (``build_review_llm_call`` pattern): ``None``
    (diagnostic mode) unless the runtime mode, the pin's model_id, and
    the transport's own gate all pass. Never raises. The runtime config
    path follows the ``episode_runner_editorial`` precedence (explicit >
    ``EDITORIAL_RUNTIME_CONFIG`` env > repo default); an unreadable
    env-named config degrades to diagnostic mode — the repo default
    production config is never substituted for it. The pin path keeps
    its repo default (pins have no env override)."""

    environment = os.environ if env is None else env
    env_name = environment.get(_EDITORIAL_RUNTIME_ENV)
    runtime = _read_json_object(_resolve_runtime_config_path(runtime_path, environment))
    if runtime is None or runtime.get("mode") != "production_model":
        if runtime is None and runtime_path is None and env_name:
            _LOGGER.warning(
                "consultation: EDITORIAL_RUNTIME_CONFIG %r is unreadable — "
                "diagnostic mode (no production fallback)",
                env_name,
            )
        return None
    pin = _read_json_object(pin_path or (_CONFIG_ROOT / PIN_RELATIVE))
    model_id = pin.get("model_id") if pin is not None else None
    if not isinstance(model_id, str) or not model_id:
        return None
    transport = runtime.get("transport")
    if transport == "openai-api":
        return _openai_consultation_call(dict(environment), pin, model_id)
    if transport in (None, "codex-exec"):
        return _codex_consultation_call(model_id)
    _LOGGER.warning("consultation: unknown transport %r, diagnostic mode", transport)
    return None


def _consultation_model_id() -> str | None:
    """The pinned consultation model id, when the pin names one (None = unattributed)."""

    pin = _read_json_object(_CONFIG_ROOT / PIN_RELATIVE)
    if pin is None:
        return None
    model_id = pin.get("model_id")
    return model_id if isinstance(model_id, str) and model_id else None


def _generation_seam() -> ModuleType:
    """Load the optional generation seam (default text path never imports it)."""

    import importlib  # noqa: PLC0415 (lazy: default path never imports the seam)

    return importlib.import_module("services.episode_cockpit.generation_call")


class GenerationCall(NamedTuple):
    """One built generation route: transport + U47 verification outcome.

    ``transport`` is None whenever the route must stay off (gated,
    non-Luna transport, unverified model) — 0 calls by construction.
    ``probe_ran`` marks the live model-echo preflight (budgeted text);
    ``probe_wall_seconds`` is its measured cost for the ledger.
    """

    transport: Callable[[str, Path | None, str], bytes] | None
    model_selected: str | None
    verified: bool
    method: str
    reason: str | None
    probe_ran: bool
    probe_wall_seconds: float


def build_generation_call() -> GenerationCall:
    """Tolerant Luna-only generation factory (never raises; gated → off).

    Luna-only: only the codex-exec transport with the pinned model may
    generate — openai-api/Image API/Web/other-agent fallbacks are never
    built. The U47 model-echo preflight proves the actually-selected
    model answers as the pinned id; anything else stays unverified.
    """

    seam = _generation_seam()
    model_pin = _consultation_model_id()
    runtime = _read_json_object(_resolve_runtime_config_path(None, dict(os.environ)))
    if runtime is None or runtime.get("mode") != "production_model":
        return GenerationCall(transport=None, model_selected=model_pin,
            verified=False, method="transport-gated",
            reason="consultation runs in diagnostic mode; generation stays off",
            probe_ran=False, probe_wall_seconds=0.0)
    if runtime.get("transport") == "openai-api":
        return GenerationCall(transport=None, model_selected=model_pin,
            verified=False, method="luna-only",
            reason="generation needs the Luna codex-exec transport; "
            "no Image API/Web/other-agent fallback is built",
            probe_ran=False, probe_wall_seconds=0.0)
    if not model_pin:
        return GenerationCall(transport=None, model_selected=None,
            verified=False, method="model-pin-missing",
            reason="the model pin names no model; refusing before any image call",
            probe_ran=False, probe_wall_seconds=0.0)
    try:
        from services.cli.live_editorial_codex import (  # noqa: PLC0415 (lazy CLI-side transport)
            make_codex_runner,
        )
        runner = make_codex_runner()
    except Exception as error:  # noqa: BLE001 (gate refusal degrades to off; never raises)
        _LOGGER.warning("generation: codex transport gated (%s)", error)
        return GenerationCall(transport=None, model_selected=model_pin,
            verified=False, method="transport-gated",
            reason=f"the codex CLI gate refused ({error}); generation stays off",
            probe_ran=False, probe_wall_seconds=0.0)
    image_transport = seam.codex_image_transport(
        runner, timeout_s=seam.REQUEST_TIMEOUT_SECONDS
    )
    started = time.monotonic()

    def probe() -> str:
        return runner(
            seam.IDENTITY_PROMPT, model=model_pin, images=(),
            timeout_s=seam.REQUEST_TIMEOUT_SECONDS,
        )

    verification = seam.verify_generation_model(
        transport="codex-exec", model_pin=model_pin, probe=probe
    )
    wall = time.monotonic() - started
    if not verification.verified:
        return GenerationCall(transport=None,
            model_selected=verification.model_selected, verified=False,
            method=verification.method, reason=verification.reason,
            probe_ran=True, probe_wall_seconds=wall)
    return GenerationCall(transport=image_transport,
        model_selected=verification.model_selected, verified=True,
        method=verification.method, reason=None,
        probe_ran=True, probe_wall_seconds=wall)


def _specs_from_request(
    panel_request: ConsultationPanelRequestV1 | None,
) -> list[PanelSpecV1]:
    """Concrete specs: explicit specs, else one role-a ask per frame_ref."""

    if panel_request is None:
        return []
    return [
        *panel_request.specs,
        *(PanelSpecV1(frame_ref=frame_ref, role="a")
          for frame_ref in panel_request.frame_refs),
    ]


def _panel_caption(spec: PanelSpecV1) -> PanelCaptionV1:
    if spec.role == "real_frame":
        unconfirmed = ("撮影素材の切り出しであり、生成した見本ではない",)
    else:
        unconfirmed = ("生成した見た目の案であり、実映像の確認ではない",)
    return PanelCaptionV1(
        subject=spec.subject or "",
        scene_note=spec.scene_note or "",
        changes=spec.changes or "",
        unconfirmed=unconfirmed,
    )


def _panel_prompt(proposal: ConsultationProposalV1, spec: PanelSpecV1) -> str:
    subject = spec.subject or proposal.title
    scene_note = spec.scene_note or ""
    changes = spec.changes or ""
    return (
        "Generate one storyboard panel image for the consultation proposal "
        f"{proposal.proposal_id} ({subject}). Scene note: {scene_note}. "
        f"Requested changes: {changes}. When a frame is attached, base the "
        "composition on that same frame. Reply with ONLY a JSON envelope "
        '{"image_base64": "<PNG bytes as base64>"} — no prose.'
    )


def _resolve_panel_frame(
    episode_dir: Path, frame_ref: str | None
) -> Path | None:
    if not frame_ref:
        return None
    candidate = episode_dir / frame_ref
    try:
        if candidate.is_file():
            return candidate
    except OSError:
        return None
    return None


